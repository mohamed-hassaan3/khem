#!/usr/bin/env bash
#
# Install Umami (visitor analytics) on the KHEM VPS. Run as root, from a
# directory holding the deploy/umami/ files:
#
#   scp deploy/umami/* root@<ip>:/root/umami/
#   ssh root@<ip> bash /root/umami/provision-umami.sh
#
# Idempotent, in the style of deploy/provision.sh: every step checks before it
# acts, so a re-run is safe and is how an upgrade of the compose file is
# applied. It installs Docker, writes the secrets once, starts Umami on
# 127.0.0.1:3001 and installs the nightly backup. It does NOT touch nginx or
# TLS — those wait for DNS (src/docs/umami-analytics.md, "First-time setup").
#
# Layout it creates:
#   /srv/umami/docker-compose.yml   copied from this directory
#   /srv/umami/.env                 secrets (600, root) — written once, never overwritten
#   /srv/umami/backup-umami.sh      nightly pg_dump
#   /srv/umami/backups/             dumps, 14 days kept

set -euo pipefail

[[ ${EUID} -eq 0 ]] || { echo "Run as root." >&2; exit 1; }

export DEBIAN_FRONTEND=noninteractive
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UMAMI_ROOT=/srv/umami

log() { printf '\n==> %s\n' "$*"; }

for file in docker-compose.yml backup-umami.sh umami.cron; do
  [[ -f "${SRC_DIR}/${file}" ]] || { echo "Missing ${SRC_DIR}/${file}" >&2; exit 1; }
done

log "Docker Engine + compose plugin (Docker's signed apt repository)"
if ! docker compose version >/dev/null 2>&1; then
  apt-get update -y
  apt-get install -y --no-install-recommends ca-certificates curl
  install -d -m 0755 /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  # shellcheck disable=SC1091
  CODENAME="$(. /etc/os-release && echo "${VERSION_CODENAME}")"
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -y
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
systemctl enable --now docker >/dev/null
docker compose version

log "Directory layout under ${UMAMI_ROOT}"
install -d -m 0700 -o root -g root "${UMAMI_ROOT}" "${UMAMI_ROOT}/backups"
install -m 0644 -o root -g root "${SRC_DIR}/docker-compose.yml" "${UMAMI_ROOT}/docker-compose.yml"
install -m 0700 -o root -g root "${SRC_DIR}/backup-umami.sh" "${UMAMI_ROOT}/backup-umami.sh"

log "Secrets (${UMAMI_ROOT}/.env)"
if [[ -s "${UMAMI_ROOT}/.env" ]]; then
  echo "Exists — left untouched (regenerating would sign everyone out and orphan the database)."
else
  # Values never reach the terminal or the shell history: generated into the
  # file directly, under a umask that makes it 600 from the first byte.
  (
    umask 077
    {
      echo "# Generated by provision-umami.sh on $(date -u +%F). Never commit, never rotate casually."
      echo "POSTGRES_PASSWORD=$(openssl rand -hex 32)"
      echo "APP_SECRET=$(openssl rand -hex 32)"
      echo "TWO_FACTOR_ENCRYPTION_KEY=$(openssl rand -hex 32)"
    } > "${UMAMI_ROOT}/.env"
  )
  echo "Written (600, root)."
fi
chmod 600 "${UMAMI_ROOT}/.env"
chown root:root "${UMAMI_ROOT}/.env"

log "Start Umami"
cd "${UMAMI_ROOT}"
docker compose config -q
docker compose pull --quiet
docker compose up -d --remove-orphans

log "Wait for the heartbeat on 127.0.0.1:3001 (first start runs the migrations)"
for _ in $(seq 1 60); do
  if curl -fsS http://127.0.0.1:3001/api/heartbeat >/dev/null 2>&1; then
    echo "Umami is up."
    break
  fi
  sleep 3
done
curl -fsS http://127.0.0.1:3001/api/heartbeat >/dev/null \
  || { echo "Umami did not answer — see: cd ${UMAMI_ROOT} && docker compose logs umami" >&2; exit 1; }

log "Port check: 3001 must be bound to loopback only"
if ss -ltnH 'sport = :3001' | awk '{print $4}' | grep -vqE '^(127\.0\.0\.1|\[::1\]):3001$'; then
  echo "!! Port 3001 is listening on a non-loopback address. Fix docker-compose.yml before continuing." >&2
  ss -ltn 'sport = :3001' >&2
  exit 1
fi
ss -ltn 'sport = :3001'

log "Nightly backup (02:30 UTC) and its log rotation"
install -m 0644 -o root -g root "${SRC_DIR}/umami.cron" /etc/cron.d/khem-umami-backup
cat > /etc/logrotate.d/khem-umami <<EOF
${UMAMI_ROOT}/backups/backup.log {
  monthly
  rotate 6
  compress
  missingok
  notifempty
}
EOF

log "Done. Next (src/docs/umami-analytics.md, \"First-time setup\"):"
cat <<'EOF'
  1. DNS: A record  analytics → this server's IP. Wait for `dig +short analytics.khemperfumes.com`.
  2. TLS:  certbot certonly --webroot -w /var/www/certbot -d analytics.khemperfumes.com \
             --deploy-hook "systemctl reload nginx" --agree-tos -m <owner email> --no-eff-email
  3. nginx: copy khem-umami-proxy.inc to /etc/nginx/snippets/, analytics.khemperfumes.conf and the
     updated khemperfumes.conf to sites-available, symlink analytics.khemperfumes.conf into
     sites-enabled, then `nginx -t && systemctl reload nginx`.
  4. Sign in at https://analytics.khemperfumes.com as admin / umami — and follow the login policy.
EOF
