revoke all on public."NewsletterSubscriber" from public, anon, authenticated;

revoke all on function public.subscribe_newsletter(jsonb)   from public, anon, authenticated;
revoke all on function public.unsubscribe_newsletter(text)  from public, anon, authenticated;
revoke all on function public.newsletter_list(text, text, int, int)
